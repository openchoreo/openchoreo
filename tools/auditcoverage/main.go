// Command auditcoverage generates a service's audit coverage matrix: every
// audited REST operation, every exemption with its reason, which operations
// supply full resource identity, and known non-events.
//
// It serves every API server in the repo, selected with -service (see
// services.go). The REST table is common; the MCP section and known
// non-events stay per-service.
//
//	go run ./tools/auditcoverage -service openchoreo-api
//	go run ./tools/auditcoverage -service observer
//
// Reporting only, so unlike tools/auditgen its output is not wired into
// code.gen-check — TestCoverageMatrix_IsFresh is the freshness gate.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"sort"
	"strings"

	"github.com/openchoreo/openchoreo/internal/server/middleware/audit"
)

func main() {
	svcName := flag.String("service", "",
		"API server to generate the matrix for, one of: "+strings.Join(serviceNames(), ", "))
	out := flag.String("out", "",
		"Output file path (default: the service's own committed matrix)")
	flag.Parse()

	svc, ok := services[*svcName]
	if !ok {
		log.Fatalf("auditcoverage: -service must be one of: %s (got %q)",
			strings.Join(serviceNames(), ", "), *svcName)
	}

	path := *out
	if path == "" {
		path = svc.defaultOut
	}

	src, err := render(svc)
	if err != nil {
		log.Fatalf("auditcoverage: %s: %v", *svcName, err)
	}
	if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
		log.Fatalf("auditcoverage: failed to write %s: %v", path, err)
	}
	fmt.Printf("auditcoverage: wrote %s\n", path)
}

func render(svc service) (string, error) {
	ops := svc.operations()
	sort.Slice(ops, func(i, j int) bool { return ops[i].ID < ops[j].ID })

	out := fmt.Sprintf("# %s\n\n", svc.title) +
		fmt.Sprintf("Generated by `tools/auditcoverage` (`make %s`). Describes what audit ", svc.makeTarget) +
		"logging covers in code — not one deployment's `audit.policies` configuration, which can " +
		"additionally suppress publishing for a matched event without changing what's *covered* here.\n\n"

	out += renderRESTSection(ops, svc.exemptions)

	if svc.extraSections != nil {
		extra, err := svc.extraSections()
		if err != nil {
			return "", err
		}
		out += extra
	}

	out += svc.knownNonEvents
	return out, nil
}

// plural returns "" for one and "s" otherwise, so a service with a single
// audited operation doesn't render "1 audited operations".
func plural(n int) string {
	if n == 1 {
		return ""
	}
	return "s"
}

func renderRESTSection(ops []audit.Operation, exemptions map[string]string) string {
	out := fmt.Sprintf("## REST — %d audited operation%s\n\n", len(ops), plural(len(ops)))
	out += "| Operation ID | Action | Category | Resource type | Resource identity |\n"
	out += "|---|---|---|---|---|\n"
	for _, op := range ops {
		var identity string
		switch {
		case op.RESTResourceParam != "":
			identity = fmt.Sprintf("path-derived (`%s`), available even on denial", op.RESTResourceParam)
		case op.NotInOpenAPISpec:
			// A non-spec operation (Exec, Wirelogs) is hand-wired outside
			// auditgen, so this table has no generic guarantee about when its
			// handler calls SetResource relative to its authz check — unlike
			// a generated body-carried create, which always runs its handler
			// (and thus SetResource) only after authz already passed.
			identity = "handler-supplied (non-spec operation, not a body-carried REST create) — see the handler for exact timing"
		default:
			identity = "handler-supplied on success (body-carried create; unavailable on a denied/failed request)"
		}
		out += fmt.Sprintf("| %s | `%s` | %s | %s | %s |\n",
			op.ID, op.Action, op.Category, op.ResourceType, identity)
	}
	out += "\n"

	out += fmt.Sprintf("### REST exemptions (%d)\n\n", len(exemptions))
	out += "| Operation ID | Reason |\n|---|---|\n"
	ids := make([]string, 0, len(exemptions))
	for id := range exemptions {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		out += fmt.Sprintf("| %s | %s |\n", id, exemptions[id])
	}
	out += "\n"
	return out
}
